func TestPlatformCheckExtSkippedByProvide(t *testing.T) {
	packages := []pkg.Package{
		{
			Name:    "acme/foo",
			Version: "1.0.0",
			Require: map[string]string{
				"ext-curl": "*",
			},
		},
		{
			Name:    "acme/polyfill-curl",
			Version: "1.0.0",
			Provide: map[string]string{
				"ext-curl": "*",
			},
		},
	}

	reqs := collectPlatformReqs(packages)
	for _, ext := range reqs.extensions {
		if ext == "curl" {
			t.Error("ext-curl should be skipped when provided by another package")
		}
	}
}

