func TestPlatformCheckDisabled(t *testing.T) {
	vendorDir := testhelper.TempDir(t, "vendor")
	packages := []pkg.Package{
		{
			Name:    "acme/foo",
			Version: "1.0.0",
			Require: map[string]string{"php": ">=8.1.0"},
		},
	}

	if err := Generate(vendorDir, packages, "h1", false, nil, true, PlatformCheckDisabled); err != nil {
		t.Fatalf("Generate: %v", err)
	}

	if _, err := os.Stat(filepath.Join(vendorDir, "composer", "platform_check.php")); !os.IsNotExist(err) {
		t.Error("platform_check.php should not be generated when disabled")
	}

	realData, _ := os.ReadFile(filepath.Join(vendorDir, "composer", "autoload_real.php"))
	if strings.Contains(string(realData), "platform_check.php") {
		t.Error("autoload_real.php should not reference platform_check.php when disabled")
	}
}

func TestPlatformCheckPHPVersion(t *testing.T) {
	vendorDir := testhelper.TempDir(t, "vendor")
	packages := []pkg.Package{
		{
			Name:    "acme/foo",
			Version: "1.0.0",
			Require: map[string]string{"php": "^8.2"},
		},
	}

	if err := Generate(vendorDir, packages, "h2", false, nil, true, PlatformCheckFull); err != nil {
		t.Fatalf("Generate: %v", err)
	}

	data, err := os.ReadFile(filepath.Join(vendorDir, "composer", "platform_check.php"))
	if err != nil {
		t.Fatalf("read platform_check.php: %v", err)
	}
	content := string(data)

	if !strings.Contains(content, "PHP_VERSION_ID >= 80200") {
		t.Errorf("platform_check.php should check PHP >= 8.2.0, got:\n%s", content)
	}
	if !strings.Contains(content, "@generated by Composer") {
		t.Error("platform_check.php should contain generated marker")
	}

	realData, _ := os.ReadFile(filepath.Join(vendorDir, "composer", "autoload_real.php"))
	if !strings.Contains(string(realData), "require __DIR__ . '/platform_check.php'") {
		t.Error("autoload_real.php should require platform_check.php")
	}
}

