func TestGenerateCreatesAllFiles(t *testing.T) {
	vendorDir := t.TempDir()

	packages := []pkg.Package{
		{
			Name:    "acme/foo",
			Version: "1.0.0",
			Autoload: pkg.Autoload{
				PSR4: map[string][]string{
					`Acme\Foo\`: {"src/"},
				},
			},
		},
	}

	if err := Generate(vendorDir, packages, "testhash123"); err != nil {
		t.Fatalf("Generate: %v", err)
	}

	expectedFiles := []string{
		"autoload.php",
		"composer/autoload_real.php",
		"composer/autoload_static.php",
		"composer/autoload_psr4.php",
		"composer/autoload_namespaces.php",
		"composer/autoload_classmap.php",
		"composer/autoload_files.php",
		"composer/ClassLoader.php",
	}

	for _, f := range expectedFiles {
		path := filepath.Join(vendorDir, f)
		if _, err := os.Stat(path); err != nil {
			t.Errorf("missing %s: %v", f, err)
		}
	}
}

