func TestGenerateClassmap(t *testing.T) {
	vendorDir := t.TempDir()

	// Create a fake package with PHP files to scan.
	pkgDir := filepath.Join(vendorDir, "acme/mapper", "lib")
	if err := os.MkdirAll(pkgDir, 0o755); err != nil {
		t.Fatalf("MkdirAll: %v", err)
	}
	if err := os.WriteFile(filepath.Join(pkgDir, "Thing.php"), []byte(`<?php
namespace Acme\Mapper;

class Thing {}
`), 0o644); err != nil {
		t.Fatalf("WriteFile: %v", err)
	}

	packages := []pkg.Package{
		{
			Name: "acme/mapper",
			Autoload: pkg.Autoload{
				Classmap: []string{"lib"},
			},
		},
	}

	if err := Generate(vendorDir, packages, "h5"); err != nil {
		t.Fatalf("Generate: %v", err)
	}

	data, err := os.ReadFile(filepath.Join(vendorDir, "composer", "autoload_classmap.php"))
	if err != nil {
		t.Fatalf("read: %v", err)
	}
	content := string(data)

	if !strings.Contains(content, `'Acme\\Mapper\\Thing'`) {
		t.Errorf("autoload_classmap.php should contain Acme\\Mapper\\Thing, got:\n%s", content)
	}
}

func TestGeneratePSR4NotInClassmap(t *testing.T) {
	vendorDir := t.TempDir()

	// Create a fake package with only PSR-4 autoload (no explicit classmap).
	// PSR-4 classes should NOT appear in classmap in non-optimized mode —
	// they are resolved at runtime by the ClassLoader.
	pkgSrcDir := filepath.Join(vendorDir, "acme/psr4only", "src")
	if err := os.MkdirAll(pkgSrcDir, 0o755); err != nil {
		t.Fatalf("MkdirAll: %v", err)
	}
	if err := os.WriteFile(filepath.Join(pkgSrcDir, "Widget.php"), []byte(`<?php
namespace Acme\Psr4Only;

class Widget {}
`), 0o644); err != nil {
		t.Fatalf("WriteFile: %v", err)
	}

	packages := []pkg.Package{
		{
			Name: "acme/psr4only",
			Autoload: pkg.Autoload{
				PSR4: map[string][]string{
					`Acme\Psr4Only\`: {"src"},
				},
			},
		},
	}

	if err := Generate(vendorDir, packages, "h7"); err != nil {
		t.Fatalf("Generate: %v", err)
	}

	data, err := os.ReadFile(filepath.Join(vendorDir, "composer", "autoload_classmap.php"))
	if err != nil {
		t.Fatalf("read: %v", err)
	}
	content := string(data)

	if strings.Contains(content, `'Acme\\Psr4Only\\Widget'`) {
		t.Errorf("autoload_classmap.php should NOT contain PSR-4 classes in non-optimized mode, got:\n%s", content)
	}
}

