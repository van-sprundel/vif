func TestFileHash(t *testing.T) {
	// Deterministic: same input always gives same output.
	h1 := fileHash("acme/lib", "src/helpers.php")
	h2 := fileHash("acme/lib", "src/helpers.php")
	if h1 != h2 {
		t.Errorf("fileHash not deterministic: %q != %q", h1, h2)
	}

	// Different inputs give different hashes.
	h3 := fileHash("acme/lib", "src/other.php")
	if h1 == h3 {
		t.Error("different inputs should give different hashes")
	}

	// Length should be 32 (md5 hex).
	if len(h1) != 32 {
		t.Errorf("fileHash length = %d, want 32", len(h1))
	}
}

func BenchmarkGenerate(b *testing.B) {
	// Build 100 packages with PSR-4 + files.
	packages := make([]pkg.Package, 100)
	for i := range packages {
		packages[i] = pkg.Package{
			Name: fmt.Sprintf("vendor/pkg%d", i),
			Autoload: pkg.Autoload{
				PSR4: map[string][]string{
					fmt.Sprintf(`Vendor\Pkg%d\`, i): {"src/"},
				},
				Files: []string{"helpers.php"},
			},
		}
	}

	b.ResetTimer()
	for i := 0; i < b.N; i++ {
		vendorDir := filepath.Join(b.TempDir(), "vendor")
		if err := Generate(vendorDir, packages, "benchhash"); err != nil {
			b.Fatalf("Generate: %v", err)
		}
	}
}
