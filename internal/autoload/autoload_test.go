func TestGenerateFiles(t *testing.T) {
	vendorDir := t.TempDir()

	packages := []pkg.Package{
		{
			Name: "symfony/polyfill",
			Autoload: pkg.Autoload{
				Files: []string{"bootstrap.php"},
			},
		},
	}

	if err := Generate(vendorDir, packages, "h3"); err != nil {
		t.Fatalf("Generate: %v", err)
	}

	// autoload_files.php should have the md5 key.
	data, err := os.ReadFile(filepath.Join(vendorDir, "composer", "autoload_files.php"))
	if err != nil {
		t.Fatalf("read: %v", err)
	}
	content := string(data)

	expectedKey := fileHash("symfony/polyfill", "bootstrap.php")
	if !strings.Contains(content, expectedKey) {
		t.Errorf("autoload_files.php should contain key %s, got:\n%s", expectedKey, content)
	}

	// autoload_real.php should contain the files require block.
	realData, err := os.ReadFile(filepath.Join(vendorDir, "composer", "autoload_real.php"))
	if err != nil {
		t.Fatalf("read real: %v", err)
	}
	if !strings.Contains(string(realData), "$filesToLoad") {
		t.Error("autoload_real.php should contain files loading block when files exist")
	}
}

