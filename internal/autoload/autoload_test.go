func TestGeneratePSR4(t *testing.T) {
	vendorDir := t.TempDir()

	packages := []pkg.Package{
		{
			Name: "symfony/yaml",
			Autoload: pkg.Autoload{
				PSR4: map[string][]string{
					`Symfony\Component\Yaml\`: {""},
				},
			},
		},
		{
			Name: "acme/lib",
			Autoload: pkg.Autoload{
				PSR4: map[string][]string{
					`Acme\Lib\`: {"src/"},
				},
			},
		},
	}

	if err := Generate(vendorDir, packages, "h1"); err != nil {
		t.Fatalf("Generate: %v", err)
	}

	// Check autoload_psr4.php
	data, err := os.ReadFile(filepath.Join(vendorDir, "composer", "autoload_psr4.php"))
	if err != nil {
		t.Fatalf("read: %v", err)
	}
	content := string(data)

	if !strings.Contains(content, `'Acme\\Lib\\'`) {
		t.Errorf("autoload_psr4.php should contain Acme\\Lib\\ namespace, got:\n%s", content)
	}
	if !strings.Contains(content, `'Symfony\\Component\\Yaml\\'`) {
		t.Errorf("autoload_psr4.php should contain Symfony\\Component\\Yaml\\ namespace")
	}

	// Check autoload_static.php has prefixLengthsPsr4
	staticData, err := os.ReadFile(filepath.Join(vendorDir, "composer", "autoload_static.php"))
	if err != nil {
		t.Fatalf("read static: %v", err)
	}
	static := string(staticData)

	if !strings.Contains(static, "$prefixLengthsPsr4") {
		t.Error("autoload_static.php should contain $prefixLengthsPsr4")
	}
	if !strings.Contains(static, "$prefixDirsPsr4") {
		t.Error("autoload_static.php should contain $prefixDirsPsr4")
	}
}

